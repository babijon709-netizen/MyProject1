#!/bin/sh
# A/B стенд тач-аима: прежняя математика против новой на одном и том же коде
# (jni/src/aim_touch.h, флаг Params::soft). 15 сценариев: захват 30° на трубе
# 2-8 кадров игры при 12/15/60 fps, встречная и ведущая цель, дрожь кости,
# дуэль без потока камеры, просадка ФПС, завышенный коэффициент, скорость 10,
# четыре сценария смены цели (скачок на -25°, смена на бегущую цель, смена без
# потока камеры, смена кости из меню).
#
# Выходной код 1 — хотя бы один сценарий стал хуже прежнего по перелёту,
# ровности хода, скорости захвата или шлейфу ведения; у сценариев смены цели
# дополнительно по окну первых 2 с: успокоение, бросок камеры, проходы через
# цель и реверсы команды.
#
# Использование:
#   ./scripts/aim_sim.sh              прогон и таблица
#   ./scripts/aim_sim.sh 4 --csv      машиночитаемый вывод (подбор параметров)
#   ./scripts/aim_sim.sh 4 x --trace 3   потактовый трейс сценария №3
set -e
cd "$(dirname "$0")/.."
CXX=${CXX:-g++}
OUT=/tmp/xvcen_aim_sim
mkdir -p "$OUT"
$CXX -std=gnu++17 -Wall -Wextra -I jni/src -I jni/include \
    tools/aim/touch_sim.cpp -o "$OUT/touch_sim"
exec "$OUT/touch_sim" "$@"
