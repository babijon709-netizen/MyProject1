// Ворота записи в кучу: разбор /proc/<pid>/maps и причины отказа.
// Лог 21:52 показал, что по одному лишь «отклонено» причину не найти —
// тест фиксирует и правила, и то, что диагностика её называет.
#include <cassert>
#include <cstdio>
#include <cstring>
#include <string>
#include "object_data_memory.h"

using object_data::Reject;

static bool check(const std::string& maps, uint64_t addr, Reject want,
                  const char* expect_line = nullptr) {
    uint64_t lo = 0, hi = 0;
    Reject got = Reject::None;
    char line[192] = {};
    const bool ok = object_data::heap_writable_range(maps, addr, 4, lo, hi, &got, line, sizeof(line));
    if (want == Reject::None) {
        if (!ok || got != Reject::None) return false;
    } else {
        if (ok || got != want) return false;
        if (expect_line && std::strstr(line, expect_line) == nullptr) return false;
    }
    return true;
}

int main() {
    const std::string maps =
        "7000000000-7000001000 r--p 00000000 fd:01 1234   /system/lib64/libc.so\n"
        "7000001000-7000002000 rw-p 00001000 fd:01 1234   /system/lib64/libc.so\n"
        "7000002000-7000003000 rw-p 00000000 00:00 0      \n"      // anon tail of libc
        "7100000000-7100001000 rw-p 00000000 00:00 0      [heap]\n"
        "7200000000-7200001000 rw-p 00000000 00:00 0      [anon:scudo:primary]\n"
        "7300000000-7300001000 rw-p 00000000 00:00 0      [anon:UnityWhatever]\n"
        "7400000000-7400001000 rwxp 00000000 00:00 0      \n"
        "7500000000-7500001000 rw-s 00000000 00:01 999    /dev/ashmem/xxx\n";

    // Анонимная куча и известные метки проходят; причина — None.
    assert(check(maps, 0x7100000800, Reject::None));
    assert(check(maps, 0x7200000010, Reject::None));

    // Хвост файлового отображения (.bss-защита) — и причина, и строка в логе
    // (строка — сам хвост, накрывающий адрес, а не файловая перед ним).
    assert(check(maps, 0x7000002800, Reject::FileTail, "7000002000-7000003000"));

    // Большой анонимный хвост (арена аллокатора, ≥8 МБ) рядом с библиотекой —
    // это куча, а не .bss: лог 22:19 показал живое оружие в 16-МБ хвосте.
    const std::string arena_maps =
        "7000000000-7000100000 rw-p 00001000 fd:01 1234   /system/lib64/libgame.so\n"
        "7000100000-7001100000 rw-p 00000000 00:00 0      \n"   // 16 МБ арена
        "7001100000-7001500000 rw-p 00000000 00:00 0      \n";  // 4 МБ — ещё .bss
    {
        uint64_t lo = 0, hi = 0;
        assert(object_data::heap_writable_range(arena_maps, 0x7000200800, 4, lo, hi));
        assert(lo == 0x7000100000 && hi == 0x7001100000);
    }
    assert(check(arena_maps, 0x7001200800, Reject::FileTail, "7001100000-7001500000"));

    // Файловое отображение (даже с правами на запись).
    assert(check(maps, 0x7000001800, Reject::FileBacked, "libc.so"));
    assert(check(maps, 0x7500000800, Reject::FileBacked, "ashmem"));

    // Анонимное, но с меткой не из белого списка — причина «метка», строка её несёт.
    assert(check(maps, 0x7300000800, Reject::NamedRegion, "UnityWhatever"));

    // Права не те.
    assert(check(maps, 0x7400000800, Reject::Perms));

    // Адреса нет в карте.
    assert(check(maps, 0x7f00000800, Reject::NoMapping));

    // Запись пересекает границу отображения.
    assert(check(maps, 0x7100000ffe, Reject::SpansBoundary));

    // Старая сигнатура (без диагностики) ведёт себя как раньше.
    {
        uint64_t lo = 0, hi = 0;
        assert(object_data::heap_writable_range(maps, 0x7100000800, 4, lo, hi));
        assert(lo == 0x7100000000 && hi == 0x7100001000);
        assert(object_data::heap_writable(maps, 0x7200000010, 4));
        assert(!object_data::heap_writable(maps, 0x7300000800, 4));
    }

    // Битая строка рвёт разбор всей карты — причина «разбор». Адрес взят
    // ПОСЛЕ битой строки, чтобы разбор до неё дошёл, а не остановился раньше.
    assert(check("7000000000-7000001000 rw-p 00000000 00:00 0\n"
                 "не-строка-карты вообще без цифр и дефисов в шапке адреса-нет-такой-шапки-совсем-длинная-строка-чтобы-пережить-буфер-заголовка-на-сто-шестьдесят-байт-и-дальше-ещё-немного-текста-для-верности-пусть-будет-длинной-вот-так-вот-вот-ещё-чуть-чуть-чуть-совсем-немного-осталось-всё-конец-строки-почти-уже-вот-теперь-точно-конец-финал-финал-финал-ок-ок-ок-ок-ок-ок-ок-ок-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-стоп-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-конец-к\n",
                 0x8000000800, Reject::ParseAbort, "не-строка"));

    std::puts("ALL HEAP-GATE TESTS PASS");
    return 0;
}
