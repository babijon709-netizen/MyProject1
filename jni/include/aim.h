#pragma once
// Аимбот: ведёт камеру синтетическим «пальцем взгляда».
// Коэффициент град/px выводится из настройки чувствительности клиента
// (AimSensitivityScale/Gain) — автофарм доводит камеру теми же функциями.
//
// Режимов два (переключатель во вкладке «Аим»), и крутят прицел они по-разному:
//
//   AIM_MODE_TOUCH   — синтетический палец (uinput): как свайп человека;
//   AIM_MODE_MEMORY  — запись ввода взгляда прямо в память игры: поворот делает
//                      сама игра, камера едет ровно как от свайпа, но без пальца.

enum AimMode {
    AIM_MODE_TOUCH  = 0,
    AIM_MODE_MEMORY = 1,
};

void UpdateAim(float dt);
// Конец кадра оверлея (повтор оси выстрела в сайтелнт-режиме).
void AimEndFrame();
float AimSensitivityScale(bool& from_game);
float AimSensitivityGain(bool& from_game);

// Палец взгляда аимбота сейчас на экране (автофарм уступает камеру, пока он ведёт).
extern bool s_fingerDown;
// Аим ведёт цель прямо сейчас (в любом из трёх режимов). Автофарм уступает ему
// камеру по этому флагу: в режимах записи в память пальца нет, но камеру аим
// крутит, и спорить с ним фарму незачем.
extern bool g_aimActive;
// Запасной коэффициент град/px (измерено на устройстве при чувствительности 2.0).
constexpr float kAimGainAtRef = 0.10f;

// Точка, из которой аимбот водит палец (доли экрана; дефолт 74%/50%).
float AimTouchFracX();
float AimTouchFracY();

// ---- Диагностика мемори-режимов -------------------------------------------
// Запись в память игры не видна снаружи: не отличить «не нашёлся объект» от
// «пишем, но игра перезаписывает поле раньше, чем читает». Эти счётчики
// показывает меню (вкладка «Аим»): по ним на устройстве видно, какой именно
// из двух поломок произошёл.
struct AimMemDiag {
    // «Память»: MouseLook найден, m_Sensitivity прочитана.
    bool  params = false;
    // «Память»: гироскоп включён — игру не обнуляет поле ввода, а прибавляет к
    // нему своё, так что записанное может сложиться с её вводом.
    bool  gyro = false;
    // «Память»: камера хотя бы раз ответила на нашу запись (коэффициент
    // подтверждён замером, а не только настройкой игры).
    bool  responded = false;
    // «Сайлент»: ось выстрела читается.
    bool  axis = false;
    // «Сайлент»: на сколько градусов ось уведена от той, что положила игра.
    float dev = 0.f;
    // «Память»: на сколько градусов накопитель MouseLook разошёлся с
    // фактическими углами камеры. Игра каждый кадр кладёт в накопитель углы
    // камеры (MouseLook.ZJo, самое начало следующего кадра), поэтому в норме
    // разница около нуля. Большая и устойчивая — значит пишем в чужой
    // MouseLook (например, не в тот PlayerManager): записи тогда проходят
    // без отказов, а своя камера не двигается вовсе.
    float mismatch = 0.f;
    int   writes = 0, fails = 0;
    // Почему в этом кадре аим молчит. 0 — работает. Без этого кода строка
    // «объект=0» в логе читается как «потерялся MouseLook», хотя чаще всего
    // аим просто выключен условиями (меню, фрикам, «только с прицелом»).
    // Расшифровка — в aim.cpp у AimBegin.
    int   inactive = 0;
    // Состояние «в прицеле» (ADS): 1 — в прицеле, 0 — нет, -1 — не прочитано.
    // Код inactive=7 означает «режим только в прицеле, а мы считаем, что
    // прицела нет». Без этого флага не видно, виноват режим или сам признак.
    int   ads = -1;
    // Откуда взялся признак «в прицеле»: 1 — активность Aim в обработчике
    // событий игрока, 2 — флаг isAiming у оружия в руках, 3 — примешивание
    // aimFOV, 0 — цепочка не подтвердилась (тогда признак считается «не в
    // прицеле»). Когда игрок точно стоял в прицеле, а в логе прицел=0, номер
    // источника сразу говорит, какая из цепочек времёт.
    int   ads_source = 0;
    // Почему в этом кадре цель не выбрана (коды — у AimSelectTarget).
    // 0 — цель была. Отдельно от inactive: inactive = «аим выключен
    // условиями», а это = «аим активен, прицел есть, но цели нет».
    int   no_target = 0;
    // Кадры, в которых доворот не понадобился: остаток меньше мёртвой зоны,
    // то есть прицел УЖЕ на цели. Их нельзя смешивать с «цели нет» —
    // внешне оба дают «записей 0».
    int   on_target = 0;
};
const AimMemDiag& AimMemoryDiag();
