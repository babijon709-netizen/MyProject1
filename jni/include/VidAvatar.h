#ifndef VID_AVATAR_H
#define VID_AVATAR_H

// Аватарка в меню: кружок в левом верхнем углу с зацикленным ASCII-видео.
//
// В бинарник ролик НЕ вшивается: tools/video/gen_avatar.py ужимает его до
// размера кружка (176x176, 12 кадров/с) и складывает кадры обычными JPEG
// (jni/src/media/avatar_video_data.inc). Внутри — свой декодер JPEG
// (third_party/tjpgd), поэтому ни MediaCodec, ни ffmpeg, ни распаковка на
// диск не нужны: кадр читается из памяти прямо в кадре отрисовки меню.
//
// Рисуется кружок СИМВОЛАМИ, как ASCII-арт в терминале: декодированный кадр
// делится на сетку знакомест малого кегля TermMono (14 px, см. ascii.h),
// каждая ячейка становится блоком «▀▄█» или символом лестницы яркости
// « .:-=+*#%@», ячейки вне круга — пробелы. Никакой текстуры OpenGL: только
// AddText, цвет — монохром «фосфор» из темы.
//
// Анимация идёт только пока меню на экране: Draw() вызывается из отрисовки
// меню, а декодирование одного кадра 176x176 занимает ~0.3 мс (x86) / ~1 мс на
// телефоне, сборка ASCII-сетки — ещё ~0.1 мс; при 12 кадрах в секунду это ~2%
// времени кадра. Когда меню закрыто, не вызывается вообще ничего.

#include "ImGui/imgui.h"

namespace VidAvatar {

// Есть ли вшитые кадры (может не быть, если media/avatar_video.h не собран).
bool Ready();

// Нарисовать кружок. radius — радиус в пикселях, ring/back — цвета обводки и
// подложки (берутся из темы меню), dt — время кадра в секундах.
void Draw(ImDrawList* dl, float cx, float cy, float radius, float dt,
          ImU32 ring, ImU32 back);

}  // namespace VidAvatar

#endif  // VID_AVATAR_H
