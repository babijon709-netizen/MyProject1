#ifndef VID_AVATAR_H
#define VID_AVATAR_H

// Аватарка в меню: кружок в левом верхнем углу с зацикленным видео.
//
// В бинарник ролик НЕ вшивается: tools/video/gen_avatar.py ужимает его до
// размера кружка (256x256, 12 кадров/с) и складывает кадры обычными JPEG
// (jni/src/media/avatar_video_data.inc, ~0.9 МБ на весь ролик вместо 4.3 МБ
// исходного mp4). Внутри — свой декодер JPEG (third_party/tjpgd), поэтому ни
// MediaCodec, ни ffmpeg, ни распаковка на диск не нужны: кадр читается из
// памяти прямо в кадре отрисовки меню.
//
// Анимация идёт только пока меню на экране: Draw() вызывается из отрисовки
// меню, а декодирование одного кадра 256x256 занимает ~0.4 мс (x86) / ~2 мс на
// телефоне — при 12 кадрах в секунду это ~2% времени кадра, то есть в профиль
// кадра это не влезает. Когда меню закрыто, не вызывается вообще ничего.

#include "ImGui/imgui.h"

namespace VidAvatar {

// Есть ли вшитые кадры (может не быть, если media/avatar_video.h не собран).
bool Ready();

// Нарисовать кружок. radius — радиус в пикселях, ring/back — цвета обводки и
// подложки (берутся из темы меню), dt — время кадра в секундах.
void Draw(ImDrawList* dl, float cx, float cy, float radius, float dt,
          ImU32 ring, ImU32 back);

}  // namespace VidAvatar

#endif  // VID_AVATAR_H
