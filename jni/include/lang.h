#pragma once

// Переключатель языка интерфейса: русский (по умолчанию) или английский.
//
// Язык живёт здесь, а не в AppState: строки собираются в двух файлах — меню и
// визуалы ESP (game.cpp) — и game.cpp про состояние меню ничего не знает.
//
// Перевод идёт от русского оригинала: XS("Противники") и таблицы имён в
// game.cpp отдают русскую строку, а lang::text()/lang::visual() подменяют её на
// английскую, когда включён английский. Так в коде остаётся одна строка-источник
// (её видно в логе и легко найти), а переводы лежат в lang_tables.inc.

namespace lang {

enum Lang {
    LANG_RU = 0,
    LANG_EN = 1,
};

void set(Lang value);          // выбор в «Опциях»
Lang current();
bool english();

// Интерфейс («Опции», вкладки, тосты, подписи строк настроек). На вход —
// строка ровно так, как она написана в коде; неизвестная возвращается как есть.
// Служебные строки (лог автофарма) намеренно не переводятся: лог разбирают
// по русским подписям, и он должен читаться одинаково при любом языке меню.
const char* text(const char* ru);

// Подписи визуалов ESP: ресурсы, предметы, животные, ящики и оружие. Ключи —
// те же строки, что лежат в таблицах имён game.cpp.
const char* visual(const char* ru);

} // namespace lang
