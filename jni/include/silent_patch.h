#pragma once
// Перехват сеттера оси выстрела прямо в коде игры (патч в памяти).
//
// Зачем. Игра пишет ось выстрела (PlayerEventHandler.LookDirection) шесть раз
// за свой кадр: CustomCharacterController.Update — дважды, MouseLook.ZJo —
// кладёт camera.forward в конце, и три места в Features.Player.KCC. Всего
// сеттер вызывается из 15 мест. Выстрел (FPHitscan.jkX) читает ось,
// нормализует её, добавляет разброс (Random.insideUnitSphere) и пускает луч —
// то есть берёт то, что легло последним. Запись из нашего потока (он вообще
// не привязан к кадру игры: оверлей рисуется в своём окне со своим
// EGL-контекстом) выигрывает эту гонку лишь иногда.
//
// Что делаем. Подменяем первые 16 байт сеттера на переход в наш трамполин.
// Трамполин выполняет вытесненные инструкции, и если патч активен — кладёт в
// s0/s1/s2 (в этих регистрах сеттер получает вектор) нашу ось. Тогда ЛЮБАЯ
// запись оси игрой пишет наше направление: гонки нет вовсе, ось наша всегда.
//
// Безопасность:
//   * перед записью сверяем вытесняемые байты с ожидаемыми — если сборка
//     игры другая, патч не ставится вовсе (и сайлент остаётся на добое
//     серией записей, как раньше);
//   * трамполин — отдельная страница, выданная mmap: свой код мы не портим;
//   * патч снимается при выходе (SilentPatchRestore): игра продолжает жить
//     со своим кодом;
//   * пока патч не включён (SilentPatchSet(false)), трамполин не трогает
//     регистры — игра получает ровно то, что писала.
#include <cstdint>

// Поставить перехват. base — адрес, по которому загружен libil2cpp.so.
// Возвращает true, если перехват стоит (или уже стоял).
bool SilentPatchInstall(std::uint64_t il2cpp_base);

// Снять перехват и вернуть байты игры на место.
void SilentPatchRestore();

// Стоит ли перехват.
bool SilentPatchInstalled();

// Включить подмену оси (или выключить — тогда игра пишет свою ось как раньше).
// x/y/z — ЕДИНИЧНЫЙ вектор направления выстрела.
void SilentPatchSet(bool active, float x, float y, float z);
