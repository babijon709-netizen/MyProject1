#pragma once
// Память-джойстик автофарма: ходьба бота стиком через ПАМЯТЬ игры, без
// синтетического тача (прежний путь — Touch_Down_N(0, ...) по зоне стика).
//
// Куда пишем. Стик движения в этой сборке проходит несколько слоёв:
//   1) UI-стик (ассет Joystick Pack: классы Joystick/FixedJoystick/
//      FloatingJoystick, неймспейс пустой) — у него есть собственное поле
//      input (Vector2, +0x98), которое живёт между кадрами: OnDrag его пишет,
//      OnPointerUp обнуляет. Пишем туда — «двигаем стик», дальше игра сама
//      раскладывает вектор по своему вводу (дедзона, маппинг в бег);
//   2) Oxide.PlayerInputHandler — два Nullable<Vector2> (0x6C и 0x78),
//      которые игра принимает публичными сеттерами glO/uov (сырой ввод
//      стика), и PlayerInput qNa (+0x40), первые 8 байт которого —
//      MovementInput: именно этот PlayerInput игра кладёт в KCC (ke<PlayerInput>
//      по +0x210), то есть это вход контроллера;
//   3) PlayerEventHandler (Vsh).MovementInput (0x128, Vsf<Vector2>, значение
//      по +0x20) — канал движения игрока рядом с LookDirection (0x140), в
//      который мы уже пишем осью выстрела.
//
// Почему кандидатов несколько и почему они перебираются. Какой из слоёв
// реально читается игрой, из дампа не видно (тел методов там нет), а
// ошибиться нельзя: запись не туда — это либо мусор в чужом поле, либо
// камера, которую тянет «взгляд»-оверрайд. Поэтому модуль ведёт ОДИН
// кандидат за раз и проверяет результат по факту: пока стик ведём, дистанция
// до точки подхода обязана сокращаться. Не сокращается за kTrialTime —
// кандидат не работает, переходим к следующему (и обнуляем старый); поехали
// назад — кандидат ведёт явно не туда, помечаем отвергнутым. Как только
// сближение подтвердилось, кандидат закрепляется до конца сессии.
//
// Все записи идут только по проверенным объектам: класс владельца сверяется
// по имени/обратной ссылке на локального игрока ДО первой записи и повторно
// перед каждой; не сошлось — кандидат пропускается (см. why_text), а не
// пишется вслепую.

namespace farmjoy {

// Кандидаты записи, в порядке проверки (номер кандидата виден в статусе).
enum Candidate {
    C_UI_STICK = 0,   // UI-стик Joystick Pack: его input (Vector2 0x98)
    C_OVR_A    = 1,   // PlayerInputHandler: Nullable<Vector2> 0x6C (ввод стика)
    C_OVR_B    = 2,   // PlayerInputHandler: Nullable<Vector2> 0x78
    C_CHANNEL  = 3,   // PlayerEventHandler: MovementInput (Vsf, значение +0x20)
    C_INPUT    = 4,   // PlayerInputHandler: PlayerInput.MovementInput (0x40)
    C_OVR_A_S  = 5,   // 0x6C с обратной раскладкой полей Nullable<T>
    C_OVR_B_S  = 6,   // 0x78 с обратной раскладкой полей Nullable<T>
    C_COUNT    = 7,
};

// Раз в кадр фарма, до command()/observe(): кэш адресов и его периодическая
// перепроверка. dt — секунды (таймеры и скорость сближения).
void tick(float dt);

// Повести стик: x — вправо, y — вперёд, магнитуда обрезается до 1.
// Вызывать каждый кадр, пока бот идёт: значение переписывается (игра может
// обнулить поле сама). false — записать сейчас некуда (см. status().why).
bool command(float x, float y);

// Удар через память: зажать/отпустить кнопку атаки у хендлера ввода
// (PlayerInputHandler+0x68, защёлка «атака зажата»). Пока зажата, игра в
// каждом кадре сама зовёт AttackContinuously (Vsh+0x1F0).Try() ->
// FPManager.OnTry_Attack(true) -> оружие.TryAttackContinuously() — тот же путь,
// которым идёт зажатая кнопка атаки в UI, только без пальца на экране.
// Частоту ударов режет кулдаун орудия; преждевременный Try() игра просто
// отбрасывает (в отличие от тапа, который она ставила в очередь). Вызывать
// каждый кадр, пока бьём. false — записать не удалось (why — как у стика).
bool attack(bool on);

// Бег через память. Персонаж идёт пешком, если у игры не нажата кнопка бега:
// оценщик спринта хендлера в КАЖДОМ кадре переписывает PlayerInput.Sprint
// (хендлер+0x59) как «стойка стика && кнопка_бега», где кнопка — InputAction
// (LD+0x48). Величина отклонения стика бег НЕ включает (она лишь масштабирует
// скорость), поэтому одной оттянутой ручки мало — нужно inProgress у акции,
// а кнопку на экране жмёт SprintJoystickHandler (: OnScreenControl), то есть
// палец. Кнопки у бота нет, поэтому ведём состояние акции в памяти: пишем
// фазу TriggerState (Started) и держим её, пока бот идёт. Раскладку и почему
// так — см. game_offsets.h (PLAYER_INPUT_HANDLER_INPUT_ACTIONS и далее).
// Вызывать каждый кадр, пока бот ведёт стик; false — записать не удалось.
bool sprint(bool on);

// Отпустить стик, атаку и бег: обнуляем все адреса, куда писали, снимаем
// зажатие кнопки атаки и возвращаем состояние кнопки бега. Идемпотентно.
void release();

// Обратная связь для проверки кандидата: дистанция до точки подхода (м) и
// «ходьба чистая» — фаза подхода, стик ведёт вперёд, это не манёвр обхода и
// не финальный подвод. Пока «чистой» ходьбы нет, кандидат не проверяется.
void observe(float walk_dist, bool clean);

// Состояние модуля. Строку «Джойстик» в окне автофарма по просьбе владельца
// убрали (окно чистое), поэтому Status/candidate_name/why_text сейчас никем не
// читаются — оставлены как единственное окно в логику выбора слоя, если
// понадобится снова вывести диагностику на экран.
struct Status {
    int   candidate = 0;      // какой кандидат ведём сейчас (C_*)
    bool  confirmed = false;  // он подтверждён фактическим сближением
    bool  armed = false;      // стик ведём
    float x = 0.f, y = 0.f;   // последний записанный вектор
    float closing_mps = 0.f;  // измеренная скорость сближения, м/с
    int   writes = 0;         // удачных записей за сессию
    int   trials = 0;         // завершённых проб кандидатов
    int   fails[C_COUNT] = {}; // провалов по каждому кандидату (индекс — C_*)
    int   why = 0;            // почему сейчас не пишем (0 — пишем)
    unsigned sticks = 0;      // бит 1 — FixedJoystick, бит 2 — FloatingJoystick
    bool  attacking = false;  // кнопка атаки сейчас зажата нашей записью
    int   attack_why = 0;     // код последней неудачи атаки (0 — пишем)
    bool  sprinting = false;  // кнопка бега сейчас взведена нашей записью
    int   sprint_why = 0;     // код последней неудачи бега (0 — пишем)
};
Status status();

// Короткое имя кандидата (для диагностики) и код последней неудачи.
const char* candidate_name(int candidate);
const char* why_text(int why);

} // namespace farmjoy
