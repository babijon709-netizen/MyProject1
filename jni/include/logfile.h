#pragma once
// Диагностический лог: пишется файлом в Загрузки (/storage/emulated/0/Download),
// чтобы его можно было вытащить с устройства сразу после зависания.
//
// Зачем. Часть отказов видна только на устройстве и только в числах: «ось
// выстрела нашлась, но игра её перезаписывает», «адрес умер после респавна»,
// «чит замер, игра идёт». Глазами на экране этого не отличить, поэтому:
//   * LogLine — строка с меткой времени; пишется и сбрасывается сразу (после
//     зависания всё, что попало в буфер, но не во файл, уже не прочитать);
//   * LogStage — чем занят кадр прямо сейчас. Сторож (отдельный поток, память
//     игры он не трогает) раз в 0.3 с смотрит на счётчик кадров: если кадры не
//     идут, пишет в лог номер последнего кадра и стадию. По стадии видно, где
//     именно встал поток отрисовки — в чтении памяти игры, в выборе цели,
//     в записи оси или вообще в отрисовке меню.
//
// Лог нужен для разбора, а не для работы: строк немного, они короткие, файл
// ограничен по размеру (перезаписывается по кругу).

// Стадии кадра. Порядок по ходу кадра; сторож печатает имя последней.
enum LogStageId {
    kStageNone = 0,        // вне кадра
    kStageFrameBegin,      // начало кадра, сброс кэшей памяти
    kStageEsp,             // чтение и отрисовка ESP
    kStageAimSelect,       // выбор цели (общий для всех режимов)
    kStageAimRead,         // чтение памяти режима (ось выстрела / накопитель углов)
    kStageAimWrite,        // запись в память игры
    kStageAimTouch,        // инъекция касания
    kStageFarm,            // автофарм
    kStageMenu,            // отрисовка меню
    kStageFreecam,         // фрикам: полёт камеры
    kStageFrameEnd,        // конец кадра (смена буфера)
    kStageCount
};

void LogOpen();
void LogClose();
// Строка в лог: метка времени «ММ-ДД ЧЧ:ММ:СС.ммм (+секунд от старта)».
void LogLine(const char* fmt, ...);
// Отметить стадию кадра (последняя попадёт в лог, если кадр встанет).
void LogStage(int stage);
// Счётчик кадров: по нему сторож видит, что отрисовка идёт.
void LogFrameBeat(unsigned long frame);
// Запустить сторожа (один раз, из main).
void LogWatchdogStart();
