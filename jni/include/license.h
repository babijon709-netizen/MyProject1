#include <cstdint>

namespace license {

// Блокирующая проверка при запуске. Нет сети — пробует grace-кэш,
// нет ключа/кэша — завершает процесс. При успехе запускает фоновые
// потоки: heartbeat (kill-switch живёт там) и сторож срока ключа.
void Gate();

// true после команды kill/ban/expired/тампер: главный цикл должен завершиться.
bool Dead();

// Серверная сессия (случайное число с каждого heartbeat). Можно мешать
// в критичные константы/оффсеты — без живого сервера чужой патч цикла
// получит мусор. См. PROTECTION.md, раздел «что ещё усилит».
uint32_t SessionMask();

} // namespace license
