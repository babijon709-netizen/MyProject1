#pragma once
#include <array>
#include <cstdint>

// Мгновенный подбор: ускорение ШТАТНОГО переноса предметов в окнах лута.
//
// Что делает игра. «Забрать всё» в окне лута (ящик, труп, рюкзак — то, что
// открывается, Oxide.LootObject), сбор лута с земли и «быстрая загрузка» — это
// корутины UniTask. За одно возобновление они переносят ОДИН слот и ждут
// 0.35 с до следующего:
//
//   <CollectAllItems>d__6.MoveNext -> PlayerInventory.FYj(kind, slot)
//                                  -> await WaitForSeconds(0.35, ignoreTimeScale)
//
// Бочка сюда не входит: её не открывают, а разбивают (Oxide.MineableObject),
// содержимое падает на землю и уходит через поток зоны подбора.
//
// 0.35 — литерал в коде (`ldr s0,[x8,#imm]` перед вызовом), поэтому менять его
// можно только правкой инструкций libil2cpp.so, чего этот проект не делает.
// Снаружи процесса доступен сам объект ожидания, который корутина выделила в
// управляемой куче: запись elapsed = duration заставляет ИГРУ возобновить
// корутину на следующем же тике PlayerLoop, а не через 0.35 с. Перенос, порядок
// слотов и клиентский запрос остаются штатными — убирается только пауза.
//
// Потолок. Одно возобновление за кадр игры: корутину крутит чужой PlayerLoop,
// и из внешнего процесса нельзя выполнить её дважды за кадр. Полный контейнер
// стоит кадра на слот (~16 мс при 60 fps, ~7 мс при 144) вместо 0.35 с на слот.
// Подробности и почему нет однопроходного варианта — в FAST_LOOT.md.
//
// Память. Единственная запись — 4 байта `elapsed` объекта ожидания, прошедшего
// полную проверку принадлежности, и только через гейт анонимной кучи. Ни
// инструкции, ни данные библиотек, ни планировщик, ни указатели продолжений, ни
// токены отмены не меняются. Возвращать нечего: игра сама обнуляет оба float'а,
// когда возвращает объект в пул, поэтому выключенная функция следа не оставляет.

namespace loot {

// Off — выключено; Waiting — включено, но сейчас нет живой корутины сбора (окно
// лута закрыто или она не в ожидании); Active — найдено своё ожидание и снято;
// Failed — образ игры не поддержан (чужая сборка, следы старого патча
// инструкций) или память не читается/не пишется.
//
// Failed не обязательно означает «не работает ничего»: точки кода проверяются по
// потокам, и поток с чужим патчем задержки отключается сам — образ отклоняется
// целиком, только когда не уцелел ни один. Какие потоки уцелели, видно в
// Diagnostics::flows. Изменённое тело `Run` поток не отключает: оно попадает в
// Diagnostics::hooked вместе с прочитанными словами.
enum class Status { Off, Waiting, Active, Failed };

// Какая именно штатная корутина ускорена: окно лута, сбор с земли или «быстрая
// загрузка» того же окна.
enum class Kind { None = -1, Container = 0, Pickup = 1, FastLoad = 2 };

// Почему отказ. Журнал в этой сборке выключен (LogLine — no-op), поэтому
// причина и одно число к ней показываются прямо в меню: по ним видно, что
// именно не сошлось — версия образа, оставшийся в процессе старый патч,
// разрешение класса или гейт кучи.
enum class Reason {
    None = 0,
    Image,      // build-id не совпал с таблицей (или не прочитался)
    Patched,    // точка прежнего патча изменена: в процессе старый инструмент
    Code,       // код образа не читается (точки таблицы вне доступной памяти)
    Helper,     // PlayerLoopHelper не разрешается через слот TypeInfo
    Runners,    // runners[] не читается, пуст или длиннее ожидаемого
    Read,       // память объекта ожидания не читается
    Write,      // гейт кучи или сама запись отказали
    Timer,      // duration/elapsed вне границ
};

struct Diagnostics {
    Status status = Status::Off;
    Kind kind = Kind::None;
    Reason reason = Reason::None; // смысл detail — см. reason
    // Битовая маска потоков переноса, прошедших проверку (bit i — Kind i).
    // Поток с чужим патчем или изменившимся кодом отключается сам, не утягивая
    // за собой остальные; 0 при отказе образа, все биты — в штатном случае.
    uint32_t flows = 0;
    // Поток, у которого инструкции `Run` в процессе отличаются от образа:
    // модифицированный клиент или чужой хук. Отказом это не считается —
    // принадлежность ожидания проверяется по именам классов и по указателю
    // метода делегата, а не по телу `Run`, — но молчать об этом нельзя: слова
    // приводятся как прочитались, чтобы было видно, что именно там стоит.
    uint32_t hooked = 0;                    // маска таких потоков
    uint64_t hooked_run = 0;                // RVA Run первого из них
    std::array<uint32_t, 5> hooked_code{};  // 4 слова пролога + ветка
    // Число к причине: первые 8 байт прочитанного build-id (Image), RVA точки
    // (Patched/RunShape), указатель класса (Helper), прочитанная длина
    // (Runners), адрес (Read/Write), биты duration|elapsed (Timer).
    uint64_t detail = 0;
    int timing = -1;              // PlayerLoopTiming раннера, где найдено ожидание
    uint64_t expired = 0;         // сколько ожиданий снято (≈ сколько пауз убрано)
    uint64_t races = 0;           // объект ушёл из-под записи и был исправлен
    uint64_t scans = 0;           // сколько проходов по раннерам сделано
};

inline const char* reason_name(Reason r) {
    switch (r) {
        case Reason::Image:    return "image";
        case Reason::Patched:  return "patched";
        case Reason::Code:     return "code";
        case Reason::Helper:   return "helper";
        case Reason::Runners:  return "runners";
        case Reason::Read:     return "read";
        case Reason::Write:    return "write";
        case Reason::Timer:    return "timer";
        default:               return "none";
    }
}

inline const char* kind_name(Kind k) {
    switch (k) {
        case Kind::Container: return "container";
        case Kind::Pickup:    return "pickup";
        case Kind::FastLoad:  return "fastload";
        default:              return "none";
    }
}

} // namespace loot

