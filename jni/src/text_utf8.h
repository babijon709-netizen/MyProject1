#pragma once
//
// Копирование строки в буфер фиксированного размера с обрезкой по границе
// символа UTF-8.
//
// Зачем отдельный файл: русские подписи в интерфейсе копируются в буферы то
// snprintf'ом, то memcpy/strncpy, и любой такой срез режется по БАЙТУ. Разрезанная
// посередине последовательность UTF-8 рисуется «ромбиком» — ровно то, что игрок
// видел в тосте («Русский» в буфере на 8 байт обрезался до половины буквы «и»).
// Для английского текста это незаметно (однобайтные символы), для русского — нет.
//
// Заодно проверяются вход и перекрытие длин: memcpy(out, tmp, cap) с cap больше
// размера источника читал за концом источника, а это уже порча стека.

#include <cstddef>

// Скопировать src в dst (ёмкость cap байт, включая нуль) и отрезать хвост
// недописанного символа UTF-8, чтобы в буфере не осталось половинки.
inline void CopyTextUtf8(char* dst, size_t cap, const char* src) {
    if (!dst || cap == 0) return;
    dst[0] = '\0';
    size_t n = 0;
    while (src && src[n] && n + 1 < cap) { dst[n] = src[n]; ++n; }
    dst[n] = '\0';
    // Находим начало последней последовательности: у продолжений старшие биты 10.
    size_t start = n;
    while (start > 0 && ((unsigned char)dst[start - 1] & 0xC0) == 0x80) --start;
    if (start > 0) --start;
    const unsigned char lead = (unsigned char)dst[start];
    size_t need = 1;
    if (lead >= 0xF0) need = 4;
    else if (lead >= 0xE0) need = 3;
    else if (lead >= 0xC0) need = 2;
    if (n - start < need) dst[start] = '\0';   // символ не влез целиком
}
