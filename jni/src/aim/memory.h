#pragma once
// aim/memory.h — Такт мемори-аима: абсолютные углы вместо пальца.
//
// Всё, что модуль отдаёт наружу: сюда смотрят те модули, которым нужны эти
// типы, данные и функции. Реализация — в aim/memory.cpp.
//
// Зачем отдельный контроллер. У тач-аима вся сложность — в петле «палец ->
// камера -> экранная ошибка»: квант цифровера, задержка отклика на два кадра,
// обучение град/px, ожидание подтверждения. У мемори-аима этой петли нет:
// углы прицела известны напрямую, а запись абсолютная, поэтому доворот — это
// один шаг по остатку ошибки. Здесь остаётся только политика шага: мёртвая
// зона (чтобы не дрожать на шуме чтения), ограничение на кадр и перевод
// «Скорости» из меню в долю ошибки за такт.
#include "app/common.h"
#include "aim/controller.h"

// ---- Функции, которые видят другие модули ----

// Один такт мемори-аима: из текущих углов прицела (yaw_now, pitch_now) и цели
// (target.yaw/target.pitch — смещения от прицела в градусах) получить новые
// абсолютные углы.
//
//   speed       — слайдер «Скорость» (1..10), тот же, что у тач-режима;
//   world_dist  — дистанция до цели, м: по ней считается мёртвая зона (3 см в
//                 мире цели), < 1 значит «неизвестна»;
//   yaw_out/pitch_out — куда поставить прицел.
//
// false — доворачивать нечего: цель внутри мёртвой зоны, писать не нужно.
bool AimMemoryStep(const AimTarget& target, float dt, float speed, float world_dist,
                   float yaw_now, float pitch_now, float& yaw_out, float& pitch_out);
