#pragma once
// aim_mem.h — Мемори-аим: поворот прицела записью в память игры.
//
// Всё, что модуль отдаёт наружу: сюда смотрят те модули, которым нужны эти
// типы, данные и функции. Реализация — в aim_mem.cpp.
//
// Зачем отдельный слой. Тач-аим водит палец через /dev/uinput: на части
// устройств инъекция не поднимается (нет прав на uinput), а где поднимается —
// поворот идёт через палец, квант цифровера и настройку чувствительности. Этот
// модуль двигает прицел там, где игра сама хранит поворот, и ничего не знает
// ни про тач, ни про экран.
//
// Куда именно писать — модуль не угадывает, а ПРОВЕРЯЕТ: пробует дорожки по
// очереди и смотрит по настоящим углам прицела, повернулся ли он ровно на
// столько, сколько просили. Поэтому состояние наружу — это результат измерения:
// либо «работает, дорожка такая-то», либо «не поддерживается, причина такая-то».
//
// Меню показывает это словами (вкладка «Аим», режим «Мемори»), а аим по
// результату самотеста либо ведёт цель записью в память, либо остаётся на
// тач-режиме.
#include "esp/common.h"

// ---- Типы модуля ----

// Состояние самотеста.
enum MemAimState {
    MEM_AIM_IDLE = 0,      // режим ещё не включали — ничего не проверено
    MEM_AIM_PROBING,       // идёт проверка дорожек
    MEM_AIM_READY,         // дорожка найдена и подтверждена
    MEM_AIM_UNSUPPORTED,   // ни одна дорожка не подтвердилась
};

// Дорожка записи (выбирается самотестом).
enum MemAimPath {
    MEM_PATH_NONE = 0,
    MEM_PATH_STATE_QUAT,   // в MouseLook лежит кватернион поворота
    MEM_PATH_STATE_DEG,    // в MouseLook пара float: yaw и pitch в градусах
    MEM_PATH_STATE_RAD,    // то же в радианах
    MEM_PATH_INPUT,        // поле накопленного ввода: игра применяет его сама
    MEM_PATH_TRANSFORM,    // поворот узла прицела в иерархии Transform
};

// Причина отказа (для строки статуса в меню).
enum MemAimReason {
    MEM_REASON_NONE = 0,
    MEM_REASON_NO_MOUSE_LOOK,   // не нашли MouseLook локального игрока
    MEM_REASON_NO_ANGLES,       // углы прицела не читаются — нечем проверять
    MEM_REASON_NO_FIELD,        // поля поворота в MouseLook не нашлись
    MEM_REASON_WRITE_LOST,      // запись принимается, но не доворачивает прицел
};

// ---- Функции, которые видят другие модули ----

int esp_mem_aim_state();
int esp_mem_aim_path();
int esp_mem_aim_reason();

// Один такт самотеста и сторожа. Зовётся из аима, пока включён режим «Мемори».
void esp_mem_aim_tick(float dt);

// Перепроверить всё заново (перепривязка, смена мира, смерть/респавн).
void esp_mem_aim_reset();

// Режим «Мемори» только что включили: подобрать дорожку немедленно. Отличие от
// esp_mem_aim_reset в том, что после предыдущего отказа ждать нечего — человек
// ждёт наведения сейчас, поэтому пауза повтора обнуляется.
void esp_mem_aim_power_on();

// Текущие углы прицела (градусы; та же система, что у esp_aim_camera_angles).
// Берутся из самой дорожки, когда она есть: у STATE_* и TRANSFORM они свежие,
// без задержки кадра. false — углы не читаются ниоткуда.
bool esp_mem_aim_read_angles(float& yaw_deg, float& pitch_deg);

// Поставить прицел на абсолютные углы. Это и есть весь аим: контроллер считает
// новые углы, а запись делает игра своим же кодом. false — дорожки нет.
bool esp_mem_aim_apply(float yaw_deg, float pitch_deg);
