#pragma once
// app/diag_log.h — Журнал здоровья: что чит делал, когда «всё выключилось».
//
// Зачем он есть. «На некоторых устройствах чит выключается сам через некоторое
// время» и «ники мерцают после смерти» — это поломки, которые случаются на
// чужом устройстве, один раз в несколько минут, и по одному описанию их можно
// только угадывать. Здесь пишется ровно то, по чему такой случай разбирается
// по факту: когда потерялась привязка и почему (errno, фаза чтения, счётчики),
// сколько раз сторож сбрасывал кэши мира и с какой частотой шли кадры, когда
// переоткрывали /proc/<pid>/mem, что делал поток переподключения тача, падал ли
// swap буфера оверлея.
//
// Куда пишется: <каталог конфигов>/xvcen_health.log (рядом с конфигами, см.
// ui/config.cpp — на устройстве это /storage/emulated/0/benzhack/). Пишутся
// только события и «пульс» раз в 30 с, поэтому файл растёт на килобайты в час;
// дорос до мегабайта — переписывается заново, прошлый остаётся в .1.
//
// Журнал включён ВСЕГДА и на всех устройствах: ровно такую поломку нельзя
// поймать, если включать запись по просьбе — к моменту просьбы она уже прошла.
//
// Зависимостей у модуля нет (stdio + мьютекс), поэтому его зовут и приложение
// (app/attach.cpp), и слой ESP (esp/boxes.cpp, esp/transform.cpp), и слой
// отрисовки (Android_draw/draw.cpp) — как общую утилиту вроде mem_io.h.
#include <stddef.h>

// ---- Функции, которые видят другие модули ----

// Открыть журнал в каталоге dir (его создаёт вызывающий). Зовётся один раз из
// main() до всего остального.
void diag_init(const char* dir);

bool diag_enabled();

const char* diag_path();

// Поймать фатальные сигналы (SIGSEGV, SIGBUS, SIGABRT, SIGILL, SIGFPE) и
// записать сам факт падения в журнал: «чит выключился сам» может быть и
// падением процесса, а тогда без этой строки о причине не узнать ничего —
// система оставляет только «процесс завершился». Обработчик пишет в уже
// открытый файл через write() (без мьютекса и без stdio — в обработчике
// сигнала это единственный безопасный путь), затем повторяет сигнал с
// поведением по умолчанию, чтобы система увидела обычное падение.
// Зовётся один раз из main() после diag_init.
void diag_install_crash_handler();

// Строка о самом процессе для «пульса»: память (RSS), открытые дескрипторы,
// число потоков и oom_score_adj. По ней видно, не течёт ли процесс и не
// подбирается ли к нему системный убийца памяти (на планшетах с малым объёмом
// RAM выгрузка чужого процесса выглядит ровно как «чит выключился сам»).
void diag_self_stats(char* out, size_t size);

// Одно событие: tag — короткое имя подсистемы («attach», «esp», «touch»,
// «draw»), fmt — printf-формат. Строку модуль дополнит секундами с запуска.
// Одинаковые события, повторяющиеся чаще раза в 2 с, схлопываются в «×N»:
// так журнал остаётся читаемым, когда что-то молотит в цикле.
void diag_log(const char* tag, const char* fmt, ...) __attribute__((format(printf, 2, 3)));
