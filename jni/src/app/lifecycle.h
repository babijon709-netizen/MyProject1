#pragma once
// app/lifecycle.h — Признаки жизни процесса (main_thread_flag, g_frame_done).
//
// Всё, что модуль отдаёт наружу: сюда смотрят те модули, которым нужны эти
// типы, данные и функции. Реализация — в app/lifecycle.cpp.
#include "app/common.h"

// ---- Данные модуля ----

extern std::atomic<bool> main_thread_flag;

extern std::atomic<bool> g_frame_done;

// ---- Данные модуля: сторож кадра ----
//
// Зачем. «Чит в один момент полностью завис» — это когда главный поток встал
// посреди кадра и не возвращается (заблокировался на хранилище, на обмене с
// системой, на снятии кадра). Снаружи это выглядит одинаково при любой причине,
// а в журнале от такой поломки не оставалось вообще ничего: последний пульс и
// тишина. Здесь отмечается, НА КАКОМ ШАГЕ стоит кадр и когда он последний раз
// завершился, — по этим двум числам поток привязки понимает, что кадр встал, и
// пишет строку с местом остановки и состоянием потока.

extern std::atomic<const char*> g_frame_stage;      // шаг кадра (статическая строка)

extern std::atomic<unsigned long long> g_frame_count;   // сколько кадров нарисовано

// Время (mono-секунды) последнего ЗАВЕРШЁННОГО кадра. Пишется главным потоком.
extern std::atomic<double> g_frame_heartbeat;

extern pthread_t g_main_thread;                     // поток кадра: его и будим

// Идентификатор потока кадра в ядре (/proc/self/task/<tid>): по нему сторож
// смотрит состояние потока в момент зависания.
extern std::atomic<int> g_main_tid;

// Отметить шаг кадра. Зовётся из main() вокруг каждого действия: строка должна
// быть статической (в журнал попадает указатель, а не копия).
void FrameStage(const char* stage);

void FrameDone();                                   // кадр закончился

// ---- Типы модуля ----

namespace prot {
static void Init() {}
}
