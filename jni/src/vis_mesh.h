#pragma once
// vis_mesh.h — сбор мешей игры в рантайме и проверка видимости по ним.
//
// Зачем. «Видим / не видим» решалось по костям: кости читаются и проецируются —
// значит цель на экране. Между глазом и костью может быть стена, шкаф или борт
// машины, и аим уезжал в неё. Спросить игру (Physics.Raycast) нельзя: это
// вызов внутри чужого процесса, а мы читаем память снаружи — без инъекции и
// без записи в код игры. Поэтому геометрию собираем сами: обходим дерево
// трансформов сцены, у каждого GameObject достаём меш (UnityEngine.Mesh из
// компонента), разворачиваем его вершины в мировые координаты и складываем в
// vis::World (vis_geom.h). Луч «глаз → кость» идёт уже по ней.
//
// Откуда смещения. Нативный Mesh — структура движка (Unity 6000.3.18f1), а не
// IL2CPP-класс: в dump.cs её нет, обфускатор её не трогает, смещения едут
// только вместе с версией Unity. Поэтому они ищутся РАНТАЙМОМ — тем же
// приёмом, что и раскладка иерархии трансформов (game.cpp): перебор
// кандидатов с проверкой по содержимому. Проверка здесь жёстче:
//   * число индексов делится на 3;
//   * КАЖДЫЙ прочитанный индекс меньше числа вершин (ложный указатель даёт
//     мусор, который почти всегда выходит за границы — это и отсекает)
//   * вершины конечны и укладываются в бокс разумного размера;
//   * найденная раскладка обязана подтвердиться минимум на трёх мешах.
// Сначала пробуется структурный якорь (подпись VertexData: каналы вершина /
// нормаль идут парой байтов вида 0x03,0x00,0x00,0x00 — см. vis_mesh.cpp),
// если он не сошёлся — полный перебор.
//
// Чего здесь нет. Данные берутся с CPU-стороны меша. Если игра выгрузила
// копию после отдачи в видеопамять (Read/Write выключен в импортере), читать
// нечего: диагностика `xvcen mesh` прямо об этом скажет, а тумблер будет
// молча ничего не менять (незнание — не препятствие, см. World::blocked).
//
// Политика пересборки: геометрия статична на момент сбора, поддеревья игроков
// в неё не попадают (exclude). Пересборка — при уходе глаза на
// kRebuildDistance метров от точки сбора, по возрасту kRebuildAge и при смене
// мира (vis::reset). Пока новый сбор идёт, запросы обслуживает прошлый.

#include <stddef.h>
#include <stdint.h>

#include <vector>

#include "Vector.h"
#include "game.h"

namespace vis {

// Состояние подсистемы — для меню и диагностики.
struct Stats {
    // 0 выкл, 1 ищем раскладку меша, 2 обходим сцену, 3 читаем меши,
    // 4 готово, 5 данных нет (раскладка не нашлась / CPU-копии выгружены),
    // 6 нет входа в сцену.
    int state = 0;
    int nodes = 0;        // узлов дерева, у которых прочитан меш
    int scanned = 0;      // узлов дерева обойдено
    int triangles = 0;
    int vertices = 0;
    int coarse = 0;       // узлов-боксов (меш не влез в бюджет)
    // Раскладка нативного Mesh, которой работаем (-1 = слот не найден).
    int vcount = -1, vptr = -1, stride = -1;
    int icount = -1, iptr = -1, width = -1;
    int field = -1;       // PPtr<Mesh> внутри компонента
    int via = 0;          // 0 вручную (офсеты), 1 структурный якорь, 2 перебор
    float origin[3] = {};
    double built_age = 0.0;
};

void set_enabled(bool on);
bool enabled();

// Смена мира / перезапуск игры: вся геометрия и найденная раскладка больше не
// относятся к процессу. Зовётся из esp_reset().
void reset();

// Кадровый тик. eye — глаз (камера этого кадра). entry — трансформ локального
// игрока, точка входа в сцену (от него поднимаемся к корню). players —
// PlayerManager'ы, чьи поддеревья в геометрию НЕ идут (тела едут вместе с
// хозяином и испортили бы сборку). now — mono_seconds().
void frame_tick(const Vec3& eye, uint64_t entry_transform,
                const std::vector<uint64_t>& players, double now);

// Проставить признак «перекрыт» по собранной геометрии. eye — глаз этого кадра
// (позиция камеры), его передаёт вызывающий: публикуемое состояние кадра
// собирается внутри того же обхода игроков. Точки — голова, грудь и середина
// тела из бокса: цель считается видимой, если хотя бы одна не перекрыта (один
// ложный обломок геометрии не должен гасить всю цель).
void annotate(std::vector<EspBox>& boxes, const Vec3& eye);

// Прямой запрос к собранной геометрии. false — не перекрыт ИЛИ геометрии нет.
bool segment_blocked(const Vec3& from, const Vec3& to, float* hit_fraction = nullptr);

const Stats& stats();
// Текстовый отчёт для `xvcen mesh` и лога.
size_t diag(char* out, size_t cap);

}  // namespace vis
