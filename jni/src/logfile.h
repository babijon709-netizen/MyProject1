#pragma once
// logfile.h — файловый лог диагностики на устройстве.
//
// Лог пишется САМ, в обычной работе чита: без терминальных команд и без
// отдельного прогона конвейера. Файл: <CfgDir()>/benzware.log, предыдущий
// срез — benzware.log.1 (ротация по размеру, kRotateBytes).
//
// Почему вообще файл: на устройстве иначе не понять «скелеты есть/нет» —
// сборочные логи, счётчики чтений и найденные на живой памяти смещения
// существуют только внутри процесса. Терминальная команда `xvcen skel`
// даёт то же самое, но требует ручного прогона и пользователя в Termux;
// файл пишет всё то же самое непрерывно и его просто забрать:
//
//     su -c cat /data/local/benzware/benzware.log
//
// Стоимость: строки форматируются в буфер в памяти и сбрасываются на диск
// пачками (по размеру и не чаще раза в kFlushSeconds) — по одной записи на
// диск на строку не уходит. Сами точки вызова в горячем пути редкие
// (сводка раз в kHeartbeatSeconds, отказы — не чаще раза в несколько
// секунд на правило), поэтому лог не влияет на кадр.
//
// Многопоточно: чит пишет из потока оверлея, сайлент-аима и фарма, поэтому
// буфер под мьютексом. Отказ открытия файла (нет каталога, нет прав)
// отключает лог до следующей попытки — падения и циклов не бывает.

#include <stddef.h>

enum LogStageId {
    kStageNone = 0,
    kStageFrameBegin,
    kStageEsp,
    kStageAimSelect,
    kStageAimRead,
    kStageAimWrite,
    kStageAimTouch,
    kStageFarm,
    kStageMenu,
    kStageFreecam,
    kStageFrameEnd,
    kStageCount
};

// dir — каталог лога (обычно CfgDir()). Создаётся при отсутствии. Повторный
// вызов переоткрывает файл (смена процесса-владельца, ротация вручную).
void LogOpen(const char* dir);
// Сбросить буфер и закрыть файл.
void LogClose();
// Сбросить буфер на диск немедленно (перед выходом, после аварии).
void LogFlush();
// Строка в лог: [ЧЧ:ММ:СС.ммм] текст.
void LogLine(const char* fmt, ...) __attribute__((format(printf, 1, 2)));
// Точки совместимости со старыми вызовами (смысл — тот же, что был в
// отключённом логе: метка стадии кадра и ручной сброс).
void LogStage(int stage);
void LogFrameBeat(unsigned long frame);
void LogWatchdogStart();
