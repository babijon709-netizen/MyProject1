#!/bin/sh
# Стенд доступа к памяти чужого процесса (jni/src/mem_io.h).
#
#   sh tools/memio/run.sh
#   BUILD=/tmp/memio sh tools/memio/run.sh     # куда складывать собранное
#
# Слой чтения памяти игры выбирает способ (process_vm_readv или
# /proc/<pid>/mem), переключается между ними и кэширует блоки на кадр. На
# телефоне это не проверить, поэтому стенд делает то же самое на хосте: порождает
# процесс-ребёнка со страницей узора и читает его память теми же функциями.
#
# Что проверяется: привязка и выбор способа, оба способа дают одни данные, кэш
# блоков (200 чтений = 1 syscall), сброс кэша началом кадра, запись доходит до
# ребёнка и не отдаётся из кэша, verify() ловит смерть процесса и отобранный
# доступ, привязка к несуществующему pid отклоняется.
set -e
cd "$(dirname "$0")/../.."
BUILD=${BUILD:-/tmp/memio_test}
mkdir -p "$BUILD"
# -DMEMIO_STATS включает счётчики syscall'ов: без них кэш не измерить.
g++ -std=gnu++17 -O1 -Wall -Wextra -DMEMIO_STATS -Ijni/src \
    tools/memio/memio_test.cpp -o "$BUILD/memio_test"
"$BUILD/memio_test"
