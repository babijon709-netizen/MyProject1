#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Разбор строк аима из лога автофарма — проверка «аим ведёт, а не дёргается».

Зачем. Симптом «аим дёргается» виден только в логе: рывок — это один-два кадра,
в которых палец уходит на десятки/сотни пикселей и камеру швыряет. Строка аима
пишется в тот же файл, что и автофарм (farm_debug.log), пять раз в секунду:

    AIM  t_s st err_yaw err_pitch sent_x sent_y exp exp cam cam f_x f_y cam_st

Как читать (подробности — в комментарии к farmlog::aimLine в main.cpp):
  * cam_st = 0 — настоящей оси камеры (поза Transform или ось выстрела) на
    устройстве нет, аим ведёт цель запасным коэффициентом вслепую. Это штатный
    режим: учить чувствительность не по чему, выученный gain так и остаётся 0, а
    рабочим служит запасное ИЗМЕРЕННОЕ значение 0.10 град/px (probeGainYaw в
    main.cpp). cam при этом остаётся нулём;
  * sent — шаг пальца в пикселях. У здорового ведения он сравним с
    err / 0.10, то есть примерно 10·|err|, и упирается в потолок шага
    (0.05 высоты экрана, пока коэффициент не выучен: на 1080 это 54 px), поэтому
    |sent| больше ~54 при cam_st 0 — уже повод смотреть строку;
  * exp = sent · gain — сколько градусов камеры должно было выйти из шага,
    cam — сколько вышло на самом деле. Их расхождение — ошибка чувствительности.
    На запасном коэффициенте |exp| ≈ |err| (шаг посчитан из той же ошибки), так
    что exp ≈ 0 при cam_st 0 означает строку старой сборки с запасным 0.35;
  * st 3 — палец ушёл в край зоны и его переносят в центр (EV «палец на краю»):
    нормальное событие при дальнем узле у фарма, но у аима это признак того, что
    шаги считаются неверно;
  * «рывок» здесь: |sent| ≥ kSentJump (по умолчанию 100 px), смена знака
    выученного gain между соседними строками (знак означает инверсию оси: аим
    начинает швырять камеру в другую сторону) или доля ошибки за такт больше
    0.62 (шаг почти равен ошибке). Последнее — раскачка: камера отвечает не в
    этом такте (поза отстаёт от касания на 2 кадра), и при k -> 1 петля идёт по
    err(t+1) = err(t) - k*err(t-1) с корнями |z| = sqrt(k) = 0.99, то есть
    колебания +-3..10 градусов не затухают. Устойчивый предел — половина
    ошибки за такт (kStable в main.cpp); строки, упёршиеся в потолок шага, в
    медиану не идут.

    python3 tools/aim/log_lint.py <farm_debug.log> [kSentJump]

Код возврата 1 — рывки найдены (в выводе будут строки и разбор), 0 — чисто.
"""
import re
import sys

LINE = re.compile(
    r'^AIM\s+([\d.]+) st (\d+)\s+err\s+([-+][\d.]+)\s+([-+][\d.]+)'
    r'\s+sent\s+([-+][\d.]+)\s+([-+][\d.]+)'
    r'\s+exp\s+([-+][\d.]+)\s+([-+][\d.]+)'
    r'\s+cam\s+([-+][\d.]+)\s+([-+][\d.]+)'
    r'\s+f\s+([\d.]+)\s+([\d.]+)\s+cam_st (\d+)')


def parse(path):
    rows = []
    for line in open(path, encoding='utf-8', errors='replace'):
        m = LINE.match(line.rstrip())
        if not m:
            continue
        t, st, ey, ep, sx, sy, xY, xP, cY, cP, fx, fy, cam_st = m.groups()
        rows.append(dict(t=float(t), st=int(st), err=(float(ey), float(ep)),
                         sent=(float(sx), float(sy)), exp=(float(xY), float(xP)),
                         cam=(float(cY), float(cP)), f=(float(fx), float(fy)),
                         cam_st=int(cam_st)))
    return rows


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    path = argv[1]
    jump = float(argv[2]) if len(argv) > 2 else 100.0
    rows = parse(path)
    if not rows:
        print('строк AIM в %s нет — аим ни разу не включался' % path)
        return 0

    axes = sorted({r['cam_st'] for r in rows})
    print('строк аима: %d, cam_st: %s' % (len(rows), axes))
    if axes == [0]:
        print('  настоящей оси камеры нет (поза и ось выстрела не читаются): '
              'учить чувствительность не по чему, выученный gain остаётся 0, и '
              'рабочим служит запасное ИЗМЕРЕННОЕ значение 0.10 град/px. В '
              'сборках, где аиму отдавался ещё и базис из матрицы вида, ровно '
              'здесь начинались рывки (gain со сменой знака); после разделения '
              'источников (esp_aim_camera_angles) их нет')
    print('состояния такта:', {st: sum(1 for r in rows if r['st'] == st)
                              for st in sorted({r['st'] for r in rows})})

    # Рабочий коэффициент аима = exp/sent (не зависит от ползунка скорости).
    # По нему видно, каким числом считался шаг: измеренное 0.10 даёт шаг
    # ≈10·|err|, прежнее запасное 0.35 — 2.86·|err|, то есть доводку в 3.5
    # раза медленнее. Если exp = 0 во всех строках с ошибкой, это строка сборки
    # ДО исправления — запасной коэффициент в лог не писался вовсе.
    gains = sorted(r['exp'][0] / r['sent'][0] for r in rows
                   if abs(r['sent'][0]) >= 1.0 and abs(r['exp'][0]) > 1e-6)
    if gains:
        median = gains[len(gains) // 2]
        print('рабочий коэффициент (exp/sent, медиана): %.3f град/px — шаг пальца '
              '≈%.1f·|err| (измеренное запасное 0.10 даёт ≈10·|err|, прежнее 0.35 '
              'давало 2.9)' % (median, 1.0 / abs(median) if median else float('inf')))
    elif any(abs(r['err'][0]) >= 0.3 for r in rows):
        print('рабочий коэффициент в лог не пишется (exp = 0 во всех строках с '
              'ошибкой): это сборка до исправления запасного коэффициента — шаг '
              'там считался как err/0.35, то есть в 3.5 раза меньше нужного')

    # Доля ошибки, которую контроллер подаёт за такт (exp/err — шаг в градусах,
    # делённый на ошибку). Камера отвечает не в этом такте: поза отстаёт от
    # касания на 2 кадра (замер в контроллере фарма), поэтому устойчиво не больше
    # половины. При k -> 1 петля идёт по err(t+1) = err(t) - k*err(t-1), корни
    # |z| = sqrt(k) = 0.99 — колебания с периодом 4.5 такта не затухают, и это
    # ровно «аим дёргается» (лог 16.09.2026: k = 0.98, смена знака ошибки в 45%
    # пар строк, шаги до потолка 54 px). Строки, упёршиеся в потолок шага, в
    # медиану не идут: там exp мал не из-за коэффициента, а из-за потолка.
    ceiling = max(max(abs(r['sent'][0]), abs(r['sent'][1])) for r in rows)
    steps = []
    for r in rows:
        if max(abs(r['sent'][0]), abs(r['sent'][1])) >= 0.95 * ceiling:
            continue
        for axis in (0, 1):
            if abs(r['err'][axis]) < 0.5 or abs(r['exp'][axis]) < 1e-6:
                continue
            steps.append(abs(r['exp'][axis]) / abs(r['err'][axis]))
    frac = None
    if steps:
        steps.sort()
        frac = steps[len(steps) // 2]
        print('доля ошибки за такт (exp/err, медиана): %.2f — %s'
              % (frac, 'устойчиво (предел 0.5 при отклике камеры через 2 кадра)'
                 if frac <= 0.62 else
                 'СЛИШКОМ МНОГО: при отклике камеры через 2 кадра это '
                 'незатухающие колебания ±3..10 градусов'))

    worst = max(rows, key=lambda r: max(abs(r['sent'][0]), abs(r['sent'][1])))
    print('самый большой шаг пальца: t %.2f, sent %+.1f %+.1f px при err %+.2f %+.2f'
          % (worst['t'], worst['sent'][0], worst['sent'][1],
             worst['err'][0], worst['err'][1]))

    problems = []
    if frac is not None and frac > 0.62:
        problems.append('доля ошибки за такт %.2f: контроллер подаёт почти всю '
                        'ошибку сразу, а отклик камеры приходит через 2 кадра — '
                        'ошибка не гаснет, а ходит через ноль (дёрганье)' % frac)
    for r in rows:
        for axis, name in ((0, 'yaw'), (1, 'pitch')):
            if abs(r['sent'][axis]) >= jump:
                problems.append('t %7.2f: шаг %s %+.1f px при err %+.2f (рывок)'
                                % (r['t'], name, r['sent'][axis], r['err'][axis]))

    # Смена знака выученного коэффициента: exp/sent меняет знак — ось
    # инвертируется, и следующий шаг уходит в обратную сторону.
    prev = None
    for r in rows:
        if abs(r['sent'][0]) < 1.0 or abs(r['sent'][1]) < 1.0:
            continue
        gain = r['exp'][0] / r['sent'][0]
        if abs(gain) > 1e-6:
            if prev is not None and (gain > 0) != (prev > 0):
                problems.append('t %7.2f: знак коэффициента сменился (%.3f -> %.3f) '
                                '— аим разворачивает камеру в другую сторону'
                                % (r['t'], prev, gain))
            prev = gain

    edges = sum(1 for r in rows if r['st'] == 3)
    if edges:
        print('пере-постановок пальца из края (st 3): %d' % edges)

    if problems:
        print('НАЙДЕНЫ РЫВКИ (%d):' % len(problems))
        for p in problems[:40]:
            print('  ' + p)
        if len(problems) > 40:
            print('  ... ещё %d' % (len(problems) - 40))
        return 1
    print('рывков нет: шаги пальца в пределах %g px, знак коэффициента не менялся'
          % jump)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
