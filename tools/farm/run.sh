#!/bin/sh
# Стенд контроллера автофарма.
#
# Собирает НАСТОЯЩИЙ код из jni/src/farm/controller.cpp — блок констант
# автофарма, namespace farmlog и UpdateFarm/UpdateFarmInner — вокруг заглушек
# (ImGui, тач, игра, настройки) и прогоняет сценарии, в которых задеты все
# места событий лога. NDK не нужен: это обычная сборка g++, поэтому гонять
# можно после каждой правки бота, не дожидаясь CI.
#
#   sh tools/farm/run.sh [кадров]      # по умолчанию 4700 кадров (~78 с игры)
#   BUILD=/tmp/x sh tools/farm/run.sh  # куда складывать собранное и лог
#
# Что проверяет:
#   * компиляцию контроллера с -Wall -Wextra -Wformat=2 — вызовы
#     farmlog::event() помечены format(printf,1,2), поэтому число и типы
#     аргументов в каждом месте события проверяет компилятор;
#   * что лог пишется, колонки ровные, события печатаются человеческим текстом;
#   * что на кадрах без цели (ex 3/4) нет выдуманных переходов «экстеншен не
#     найден» / «точка прицела: корпус»;
#   * что обход перекрытого узла доходит до отказа: #1 -> #2 -> #3 -> #4 -> blacklist;
#   * что без луча прицела у игры бот не тапает (удар всё равно в воздух), а
#     поджимает ближе, и что тапы возвращаются, как только луч появился;
#   * что строки «замах» и «крестик появился» несут геометрию и сырые SPOT_A/B.
#   * что мигание цели на один кадр удержано и не стоит паузы смены узла;
#   * что камень, в который упёрся собственный луч игры (прицел внутри породы),
#     бьётся: тапы есть, крестик руды появился, обходов нет — и то же по хвосту
#     лога, который присылает пользователь.
set -e
cd "$(dirname "$0")/../.."
BUILD=${BUILD:-/tmp/farm_ctrl_test}
FRAMES=${1:-4700}
mkdir -p "$BUILD/cfg"
rm -f "$BUILD/cfg"/*.log

# Регион контроллера вырезается из своего модуля по содержимому, а не по
# номерам строк: правки выше по файлу не должны ломать стенд. После разрезания
# монолита контроллер живёт в jni/src/farm/controller.cpp, строки XS — в
# jni/src/ui/xp.h.
python3 - "$BUILD" <<'PY'
import sys
build = sys.argv[1]
lines = open('jni/src/farm/controller.cpp', encoding='utf-8').read().split('\n')

start = None
for i, l in enumerate(lines):
    if l == 'namespace {' and any('kStuckTime' in x for x in lines[i:i + 80]):
        start = i
        break
assert start is not None, 'не найден блок констант автофарма'

inner = lines.index('static void UpdateFarmInner(float dt) {')
depth, end = 0, None
for i in range(inner, len(lines)):
    depth += lines[i].count('{') - lines[i].count('}')
    if depth == 0 and i > inner:
        end = i
        break
assert end is not None, 'не найден конец UpdateFarmInner'
open(build + '/ctrl.inc', 'w', encoding='utf-8').write('\n'.join(lines[start:end + 1]) + '\n')

src = open('jni/src/ui/xp.h', encoding='utf-8').read()
a = src.index('namespace xp {')
b = src.index('#define XS(s)')
c = src.index('\n', b) + 1
open(build + '/xp.inc', 'w', encoding='utf-8').write(src[a:c])
print('регион контроллера: строки %d..%d farm/controller.cpp' % (start + 1, end + 1))
PY

cp jni/include/game.h "$BUILD/game.h"
g++ -std=gnu++17 -O1 -Wall -Wextra -Wformat=2 -Wno-format-nonliteral \
    -Wno-unused-parameter -I"$BUILD" -Ijni/include -Ijni/src \
    -o "$BUILD/ctrl_test" tools/farm/ctrl_test.cpp
echo "сборка стенда: ОК"

# Стенд пишет лог в каталог из FARMLOG_DIR (заглушка каталога конфигов),
# а счётчики участков — в stderr (их проверяем ниже).
FARMLOG_DIR="$BUILD/cfg/" "$BUILD/ctrl_test" "$FRAMES" 2>"$BUILD/stderr"
cat "$BUILD/stderr"
LOG="$BUILD/cfg/farm_debug.log"
echo "--- лог: $LOG ($(wc -l < "$LOG") строк, $(wc -c < "$LOG") байт)"
echo "--- типы событий:"
grep '^EV' "$LOG" | sed 's/^EV *[0-9.]* //' | sed 's/[0-9][0-9.]*/N/g' | sort | uniq -c | sort -rn
echo "--- проверки:"
fail=0
grep -q "перекрыт: 4 обходов не помогли" "$LOG" || { echo "НЕТ отказа от перекрытого узла"; fail=1; }
# Номера обходов перекрытия должны расти: #1 -> #2 -> #3 -> #4 -> отказ.
# (После отказа стенд показывает тот же узел снова — blacklist в заглушке
# пустой, — поэтому цикл может начаться заново; важна отсутствие повторов
# подряд: именно так выглядел баг с обнулением счётчика в фазе 3.)
grep 'перекрыт: луч игры' "$LOG" | sed 's/.*обход #\([0-9]*\).*/\1/' > "$BUILD/evseq"
awk 'NR>1 && $1==prev {bad=1} {prev=$1} END{exit bad}' "$BUILD/evseq" \
    || { echo "обход перекрытия повторяет один и тот же номер — счётчик обнуляется"; fail=1; }
grep -q 'экстеншен крестика на узле не найден' "$LOG" && { echo "ложное «экстеншен не найден»"; fail=1; }
# Участок F: пока у игры нет данных рейкаста прицела (обёртка GKo пуста), удар
# не засчитывается вовсе — FPMelee.ZkX играет один On_Woosh. Тапов быть не
# должно, стик обязан поджимать ближе к узлу, а после появления луча тапы
# возвращаются. Лог 14.09.2026: 43 из 48 замахов без урона шли без луча.
grep -q 'НЕТ_ЛУЧА: кадров 1[0-9][0-9], тапов 0,' "$BUILD/stderr" \
    || { echo "бот тапал, пока у игры не было луча прицела — удары в воздух"; fail=1; }
grep -q 'стик жал кадров 1[0-9][0-9]' "$BUILD/stderr" \
    || { echo "без луча игры стик не поджимает бота к узлу"; fail=1; }
grep -q 'ПОСЛЕ_ЛУЧА: тапов [1-9]' "$BUILD/stderr" \
    || { echo "после появления луча игры тапы не вернулись"; fail=1; }
# Строка замаха обязана нести геометрию: без неё «в воздух» не отличить от
# «не засчитал серию», а сдвиг декали от коры не измерить.
grep -q 'замах: dist .* | луч .* | прицел .* узел .* | без луча ' "$LOG" \
    || { echo "в логе нет строк замаха с геометрией"; fail=1; }
grep -q 'крестик появился: источник .* SPOT_A .* why ' "$LOG" \
    || { echo "в логе нет диагностики точки крестика (SPOT_A/why)"; fail=1; }
# Участок G: мигание цели на один кадр (рескан реестра) не должно ни менять
# узел, ни ставить паузу смены — в логе 14.09.2026 так простаивал 14 с из 150.
grep -q 'МИГАНИЕ: кадров 200, миганий 5, удержано [1-9]' "$BUILD/stderr" \
    || { echo "мигание цели не удержано — бот переключается на один кадр"; fail=1; }
grep -q 'пауз_смены_после_мигания 0' "$BUILD/stderr" \
    || { echo "мигание цели всё ещё стоит паузы смены узла (0.7 с простоя)"; fail=1; }
grep -q 'цель мигнула на узел' "$LOG" \
    || { echo "в логе нет события «цель мигнула»"; fail=1; }
# Участок H: доводка камеры. Камера стенда отвечает на палец через 2 кадра (в
# логе 14.09.2026 отклик приходил через 2, реже 4..6) и с коэффициентом, который
# намеренно не равен запасному. Прежний контроллер слал 9..11 шагов подряд, не
# дождавшись отклика: шаги складывались, камера перелетала крестик, знак ошибки
# менялся и палец швырял её обратно — игрок видит это как «прицел дёргается».
# Обучатель коэффициента при этом делил поворот одного кадра на сдвиг одного
# кадра и сбрасывался 571 раз за 122 с (0.0083..1.97 град/px).
grep -q 'ДОВОДКА: кадров 4[0-9][0-9][0-9], шагов [1-9]' "$BUILD/stderr" \
    || { echo "доводка камеры не прогнана — шагов камерного пальца нет"; fail=1; }
grep -q 'стопок 0 (' "$BUILD/stderr" \
    || { echo "контроллер досылает шаг, не дождавшись ответа камеры (перелёт = дёрганье)"; fail=1; }
grep -q 'перелётов 0, смен знака [012],' "$BUILD/stderr" \
    || { echo "ошибка наведения раскачивается: камера перелетает цель"; fail=1; }
python3 - "$BUILD/stderr" <<'PYCHK' || fail=1
import re, sys
line = [l for l in open(sys.argv[1], encoding='utf-8') if l.startswith('ДОВОДКА:')]
assert line, 'в stderr нет строки ДОВОДКА'
lo, hi = (float(x) for x in re.search(r'gain ([\d.]+)\.\.([\d.]+)', line[0]).groups())
# Обучатель обязан сойтись к настоящему коэффициенту (0.30 в окне B) и не вылезти
# за полосу kGainLo..kGainHi (0.035..0.350): на запасном 0.10 он так и остался бы,
# если бы образцы не принимались.
assert hi >= 0.20, 'обучатель не пошёл за настоящей чувствительностью (max %.4f)' % hi
assert lo >= 0.034 and hi <= 0.351, 'коэффициент вылез за полосу правдоподобия %.4f..%.4f' % (lo, hi)
print('доводка: коэффициент %0.4f..%0.4f — сошёлся и в полосе' % (lo, hi))
PYCHK
# Участок I: камень, у которого луч игры упёрся в собственную породу. Лог
# 14.09.2026, узел 86a3c0: 1595 кадров, ray 0.51..0.77 м при aim_3d 1.97..2.33 м,
# blk=1 на всех кадрах, ноль тапов и два «обход (вправо)» подряд — точка прицела
# у камня лежит ВНУТРИ породы, и старая формула принимала свой же камень за
# стену. game.cpp теперь узнаёт своё попадание (m_Collider луча против
# OREHS_COLLIDER узла либо GameObject попадания против GameObject узла) и снимает
# ray_blocked, а контроллер меряет дистанцию тем же лучом, которым её меряет
# игра. Бот обязан бить: фаза удара, тапы, появившийся крестик руды — и ни
# одного кадра с blk или с манёвром обхода.
grep -q 'РУДА_СВОЙ_ЛУЧ: кадров 400, фаза3 [34][0-9][0-9], тапов [1-9]' "$BUILD/stderr" \
    || { echo "камень со своим лучом не бьётся: бот не в фазе удара или нет тапов"; fail=1; }
grep -q 'РУДА_СВОЙ_ЛУЧ:.* blk 0, обходов 0,' "$BUILD/stderr" \
    || { echo "на своём же камне бот снова уходит в обход (blk/evd в окне участка I)"; fail=1; }
grep -q 'РУДА_СВОЙ_ЛУЧ:.*крестик 1' "$BUILD/stderr" \
    || { echo "после первого удара по камню крестик руды не появился"; fail=1; }
# То же независимо, по строкам лога: участок I — самый хвост файла (400 строк).
python3 - "$LOG" <<'PYI' || fail=1
import sys
hdr = None
rows = []
for line in open(sys.argv[1], encoding='utf-8', errors='replace'):
    if line.startswith('    t_s'):
        hdr = line.split(); continue
    if line.startswith('EV') or line.startswith('#'): continue
    p = line.split()
    if hdr and len(p) >= len(hdr): rows.append(p)
assert hdr, 'в логе нет шапки колонок'
I = {n: i for i, n in enumerate(hdr)}
tail = rows[-400:]
assert len(tail) == 400, 'в хвосте лога %d строк вместо 400' % len(tail)
bad  = sum(1 for r in tail if r[I['blk']] != '0')
taps = sum(1 for r in tail if r[I['tp']] == '1')
kind = set(r[I['k']] for r in tail)
at   = sum(1 for r in tail if r[I['at']] == '1')
assert bad == 0, 'в окне участка I blk=1 на %d кадрах — свой камень снова за стену' % bad
assert taps > 10, 'в окне участка I палец удара нажат всего на %d кадрах' % taps
assert kind == {'1'}, 'в окне участка I ресурс %s, ждали только камень' % sorted(kind)
assert at > 100, 'крестик руды не стал точкой прицела (at=1 лишь на %d кадрах)' % at
print('хвост лога (участок I): blk 0 на 400 кадрах, палец удара на %d, at=1 на %d, ресурс %s'
      % (taps, at, sorted(kind)))
PYI
head -1 "$LOG" | grep -q '^# зоны бота:' || { echo "в шапке нет зон бота"; fail=1; }
[ "$fail" = 0 ] && echo "все проверки пройдены"
exit $fail
